import type { BufferGeometry } from 'three';
import { flipX, merge, tint, tube, wave, type V3 } from './geo';
import { armPoint } from './skin';
import type { GeometrySet } from './transfer';

/* Кровеносные сосуды и нервы: аорта и её ветви, полые вены, сосуды рук и ног, нервные стволы. */

const arm = (pts: V3[]): V3[] => pts.map((p) => (p[1] < 14.0 ? armPoint(p) : p));
/** Путь руки: точки левой стороны поворачиваются вместе с рукой, для правой отражаются. */
const armSide = (pts: V3[], s: 1 | -1): V3[] => (s === 1 ? arm(pts) : flipX(arm(pts)));

type Radius = number | ((t: number) => number);
const T = (pts: V3[], r: Radius, radial = 10): BufferGeometry => tube(pts, r, { radial });

function taper(a: number, b: number): (t: number) => number {
  return (t) => a + (b - a) * t;
}

export function buildArteries(): BufferGeometry {
  const list: BufferGeometry[] = [];
  // аорта: восходящая часть, дуга, грудной и брюшной отделы
  list.push(
    tube(
      [
        [0.2, 12.98, 0.2], [0.14, 13.45, 0.28], [0.17, 13.92, 0.16], [0.42, 14.14, -0.12], [0.68, 13.8, -0.4], [0.62, 13.0, -0.46], [0.5, 12.0, -0.34],
        [0.4, 11.2, -0.14], [0.33, 10.5, 0.0], [0.3, 10.05, 0.02],
      ],
      (t) => 0.145 - 0.07 * t - 0.025 * Math.max(0, t - 0.6),
      { radial: 14, segments: 220 },
    ),
  );
  // ветви дуги: плечеголовной ствол, левая сонная и левая подключичная
  list.push(T([[0.16, 13.98, 0.15], [-0.05, 14.28, 0.12], [-0.3, 14.5, 0.12]], taper(0.085, 0.07)));
  list.push(T([[0.3, 14.12, 0.0], [0.34, 14.45, 0.1], [0.38, 15.0, 0.08], [0.42, 15.4, 0.06]], taper(0.06, 0.05)));
  list.push(T(arm([[0.5, 14.1, -0.1], [0.9, 14.42, 0.0], [1.4, 14.2, 0.05]]), taper(0.07, 0.06)));
  list.push(T([[-0.3, 14.5, 0.12], [-0.36, 14.8, 0.1], [-0.38, 15.0, 0.08], [-0.42, 15.4, 0.06]], taper(0.06, 0.05)));
  list.push(T(armSide([[0.3, 14.5, 0.12], [0.9, 14.5, 0.04], [1.4, 14.2, 0.05]], -1), taper(0.07, 0.06)));
  // сонные артерии: внутренняя уходит к основанию мозга, наружная — к лицу
  for (const s of [1, -1] as const) {
    const f = (pts: V3[]) => (s === 1 ? pts : flipX(pts));
    list.push(T(f([[0.42, 15.4, 0.06], [0.4, 15.8, 0.0], [0.34, 16.05, -0.12], [0.18, 16.12, 0.0]]), taper(0.045, 0.028), 8));
    list.push(T(f([[0.42, 15.4, 0.06], [0.52, 15.7, 0.25], [0.62, 16.1, 0.4], [0.6, 16.5, 0.3]]), taper(0.04, 0.018), 8));
  }
  // виллизиев круг у основания мозга
  const ring: V3[] = [];
  for (let i = 0; i <= 20; i++) {
    const a = (i / 20) * Math.PI * 2;
    ring.push([0.2 * Math.sin(a), 16.1, -0.05 + 0.2 * Math.cos(a) * 1.1]);
  }
  list.push(tube(ring, 0.014, { radial: 6, segments: 60 }));
  // руки: подключичная → подмышечная → плечевая → лучевая и локтевая
  for (const [pts, r] of [
    [[[1.4, 14.2, 0.05], [1.62, 13.9, 0.02], [1.72, 13.2, -0.04], [1.8, 12.0, -0.12], [1.84, 10.95, -0.14]], taper(0.06, 0.045)],
    [[[1.84, 10.95, -0.14], [1.92, 10.0, -0.08], [2.04, 8.8, -0.03], [2.1, 8.2, 0.02]], taper(0.045, 0.028)],
    [[[1.84, 10.95, -0.14], [1.8, 10.0, -0.24], [1.9, 8.8, -0.26], [2.0, 8.2, -0.1]], taper(0.04, 0.026)],
    [[[2.1, 8.2, 0.02], [2.18, 7.85, 0.14], [2.32, 7.7, 0.12], [2.38, 7.5, 0.1]], 0.02],
  ] as [V3[], Radius][]) {
    list.push(T(arm(pts), r, 8));
    list.push(T(flipX(arm(pts)), r, 8));
  }
  // брюшные ветви: чревный ствол, селезёночная, печёночная, верхняя брыжеечная, почечные
  list.push(T([[0.3, 11.25, 0.02], [0.3, 11.4, 0.2]], 0.05));
  list.push(T([[0.3, 11.4, 0.2], [0.65, 11.5, 0.05], [1.0, 11.35, -0.3], [1.15, 11.3, -0.45]], taper(0.04, 0.03), 8));
  list.push(T([[0.3, 11.4, 0.2], [-0.1, 11.5, 0.3], [-0.45, 11.45, 0.35], [-0.6, 11.3, 0.4]], taper(0.04, 0.03), 8));
  list.push(T([[0.3, 11.0, 0.02], [0.3, 10.7, 0.22], [0.15, 10.35, 0.4], [-0.1, 10.0, 0.5]], taper(0.055, 0.03), 8));
  for (let i = 0; i < 6; i++) {
    const y = 10.5 - i * 0.14;
    list.push(T([[0.18 - i * 0.04, y + 0.12, 0.42], [0.05, y, 0.5], [-0.3 + (i % 2) * 0.55, y - 0.05, 0.55]], 0.014, 6));
  }
  list.push(T([[0.3, 10.65, -0.1], [0.45, 10.68, -0.34], [0.6, 10.7, -0.46]], 0.03, 8));
  list.push(T([[0.28, 10.62, -0.12], [-0.1, 10.55, -0.28], [-0.5, 10.58, -0.46]], 0.03, 8));
  // подвздошные и артерии ног
  for (const s of [1, -1] as const) {
    const f = (pts: V3[]) => (s === 1 ? pts : flipX(pts));
    list.push(
      tube(f([[0.3, 10.05, 0.02], [0.6, 9.65, 0.1], [0.85, 9.2, 0.25], [0.9, 8.7, 0.4], [0.85, 7.8, 0.4], [0.75, 6.5, 0.3], [0.64, 5.5, 0.08], [0.6, 4.85, -0.28]]), (t) => 0.1 - 0.055 * t, {
        radial: 10,
        segments: 220,
      }),
    );
    list.push(T(f([[0.6, 4.85, -0.28], [0.62, 4.3, -0.2], [0.64, 3.2, -0.18], [0.74, 1.6, -0.1], [0.92, 0.9, 0.0]]), taper(0.04, 0.02), 8));
    list.push(T(f([[0.62, 4.5, -0.22], [0.7, 4.2, 0.1], [0.68, 3.0, 0.2], [0.62, 1.4, 0.24], [0.58, 0.72, 0.5], [0.52, 0.55, 1.0], [0.46, 0.5, 1.4]]), taper(0.035, 0.014), 8));
    list.push(T(f([[0.82, 8.4, 0.38], [0.92, 7.7, 0.1], [0.92, 6.4, -0.15], [0.8, 5.3, -0.28]]), taper(0.05, 0.025), 8));
    list.push(T(f([[0.85, 9.2, 0.15], [0.7, 9.0, -0.3], [0.5, 9.1, -0.65]]), 0.04, 8));
  }
  return tint(merge(list), (_x, y) => {
    const w = 0.9 + 0.1 * wave(y, 14, 3);
    return [1, w, w];
  });
}

export function buildVeins(): BufferGeometry {
  const list: BufferGeometry[] = [];
  // верхняя и нижняя полые вены
  list.push(T([[-0.38, 13.0, 0.28], [-0.46, 13.7, 0.2], [-0.5, 14.35, 0.08], [-0.42, 14.7, 0.0]], 0.105, 12));
  list.push(
    tube([[-0.34, 12.35, 0.1], [-0.4, 11.7, -0.26], [-0.34, 11.0, -0.28], [-0.26, 10.4, -0.18], [-0.2, 10.05, -0.08]], (t) => 0.14 - 0.03 * t, { radial: 12, segments: 100 }),
  );
  list.push(T([[-0.2, 10.05, -0.08], [-0.55, 9.65, 0.05], [-0.8, 9.3, 0.2]], 0.1, 10));
  list.push(T([[-0.2, 10.05, -0.08], [0.1, 9.9, -0.1], [0.45, 9.55, 0.0], [0.8, 9.3, 0.18]], 0.09, 10));
  // плечеголовные и яремные вены: левая длиннее и пересекает среднюю линию
  list.push(T([[-0.42, 14.72, 0.0], [0.0, 14.65, 0.06], [0.5, 14.5, 0.06], [1.0, 14.35, 0.1]], 0.08, 10));
  list.push(T([[-0.42, 14.72, 0.0], [-0.6, 14.5, 0.06], [-1.0, 14.35, 0.1]], 0.08, 10));
  for (const s of [1, -1] as const) {
    const f = (pts: V3[]) => (s === 1 ? pts : flipX(pts));
    list.push(T(f([[0.5, 14.45, 0.1], [0.5, 15.0, 0.12], [0.52, 15.5, 0.08], [0.5, 15.95, -0.12], [0.45, 16.1, -0.3]]), taper(0.07, 0.04), 10));
    // вены рук: плечевая и поверхностная (латеральная подкожная)
    list.push(T(armSide([[1.35, 14.3, 0.1], [1.6, 13.85, 0.05], [1.68, 13.2, 0.04], [1.76, 12.0, -0.02], [1.8, 10.95, -0.06], [1.86, 10.0, -0.12], [1.98, 8.8, -0.12], [2.08, 8.2, -0.04]], s), taper(0.05, 0.03), 8));
    list.push(T(armSide([[1.9, 12.5, 0.14], [1.98, 11.4, 0.2], [2.0, 10.4, 0.18], [2.04, 9.2, 0.12], [2.14, 8.3, 0.08]], s), 0.022, 8));
    // вены ног: бедренная, подколенная, большая подкожная
    list.push(
      tube(f([[0.8, 9.3, 0.15], [0.84, 8.6, 0.26], [0.8, 7.6, 0.2], [0.7, 6.4, 0.14], [0.6, 5.4, -0.08], [0.58, 4.85, -0.22], [0.6, 4.2, -0.12], [0.66, 3.2, -0.12], [0.84, 1.6, -0.06], [0.94, 0.85, 0.02]]), (t) => 0.11 - 0.07 * t, {
        radial: 10,
        segments: 220,
      }),
    );
    list.push(T(f([[0.78, 8.7, 0.46], [0.68, 7.6, 0.5], [0.52, 6.2, 0.5], [0.4, 5.0, 0.42], [0.36, 3.6, 0.28], [0.4, 2.0, 0.2], [0.55, 0.9, 0.2]]), taper(0.04, 0.022), 8));
    list.push(T(f([[0.6, 4.1, -0.3], [0.66, 3.4, -0.42], [0.64, 2.6, -0.34]]), 0.025, 6));
    // почечные вены
    list.push(T(s === 1 ? [[0.62, 10.72, -0.5], [0.4, 10.68, -0.4], [-0.2, 10.62, -0.3]] : [[-0.62, 10.55, -0.5], [-0.45, 10.55, -0.4], [-0.34, 10.6, -0.3]], 0.05, 8));
  }
  // воротная вена печени и печёночные вены
  list.push(T([[-0.08, 10.7, 0.25], [-0.2, 11.0, 0.3], [-0.42, 11.3, 0.34], [-0.55, 11.4, 0.36]], taper(0.075, 0.06), 10));
  list.push(T([[-0.3, 11.8, -0.1], [-0.34, 12.1, 0.0], [-0.34, 12.3, 0.1]], 0.06, 8));
  list.push(T([[-0.5, 11.7, -0.1], [-0.4, 11.9, -0.1], [-0.34, 12.0, -0.05]], 0.04, 8));
  // лёгочные вены к левому предсердию
  return tint(merge(list), (_x, y) => {
    const w = 0.92 + 0.08 * wave(y, 12, 3);
    return [w, w, 1];
  });
}

export function buildNerves(): BufferGeometry {
  const list: BufferGeometry[] = [];
  // плечевое сплетение и нервы руки
  for (const s of [1, -1] as const) {
    const f = (pts: V3[]) => (s === 1 ? pts : flipX(pts));
    list.push(T(armSide([[0.3, 14.9, -0.38], [0.8, 14.5, -0.25], [1.3, 14.1, -0.15], [1.6, 13.6, -0.18]], s), taper(0.04, 0.03), 7));
    list.push(T(armSide([[1.6, 13.6, -0.18], [1.68, 12.5, -0.2], [1.78, 11.2, -0.28], [1.86, 9.8, -0.3], [2.0, 8.5, -0.2], [2.1, 7.6, 0.0]], s), taper(0.028, 0.012), 7));
    // седалищный нерв и его ветви
    list.push(T(f([[0.5, 9.5, -0.78], [0.78, 9.0, -0.62], [0.82, 8.0, -0.42], [0.72, 6.5, -0.36], [0.62, 5.2, -0.3]]), taper(0.07, 0.045), 9));
    list.push(T(f([[0.62, 5.2, -0.3], [0.62, 4.2, -0.22], [0.66, 3.0, -0.2], [0.84, 1.5, -0.08], [0.92, 0.85, 0.04]]), taper(0.04, 0.014), 7));
    list.push(T(f([[0.62, 5.2, -0.3], [0.9, 4.9, -0.1], [0.95, 4.2, 0.04], [0.82, 2.8, 0.16], [0.7, 1.2, 0.3], [0.6, 0.7, 0.55]]), taper(0.032, 0.012), 7));
    // бедренный нерв
    list.push(T(f([[0.3, 10.6, -0.3], [0.62, 9.6, 0.05], [0.88, 8.8, 0.42], [0.76, 7.0, 0.44], [0.62, 5.2, 0.34]]), taper(0.04, 0.02), 7));
    // блуждающий нерв вдоль сонной артерии и к органам груди
    list.push(T(f([[0.46, 16.0, -0.22], [0.46, 15.4, 0.0], [0.44, 14.6, 0.04], [0.36, 13.9, -0.1], [0.28, 13.2, -0.28], [0.2, 12.5, -0.32]]), 0.018, 6));
  }
  return tint(merge(list), (x, y) => {
    const w = 0.94 + 0.06 * wave(y * 2 + x, 8, 3);
    return [w, w, w * 0.9];
  });
}

export function buildVessels(): GeometrySet {
  return { arteries: buildArteries(), veins: buildVeins(), nerves: buildNerves() };
}

