export function buildPituitaryDiorama(): PartMeshMap {
  // 1. Гипоталамус и дно третьего желудочка с сосцевидными телами (гладкий купол без резкой внутренней щели)
  const hypoBase = smooth(
    0.28,
    E([0, 1.86, -0.18], [1.26, 0.68, 1.32], 0.5),
    // серый бугор и срединное возвышение (воронка книзу)
    E([0, 1.12, 0.24], [0.68, 0.44, 0.62], 0.4),
    // парные сосцевидные тела позади воронки
    mirrored(E([0.38, 0.96, -0.78], [0.28, 0.26, 0.28], 0.3)),
    // перемычка назад к эпиталамусу и поводку эпифиза
    capsule([0, 1.92, -1.05], [0, 1.90, -1.85], 0.34, 0.17),
  );
  const hypoGeo = attachOrganicUv(
    organicTint(
      sdfMesh(wobble(hypoBase, 3.0, 0.022, 0.3), [-1.6, 0.52, -2.1], [1.6, 2.70, 1.4], 0.075, 0.10),
      (x, y, z) => {
        const k = 0.90 + 0.10 * wave(x * 3 + y * 4 + z * 3, 4, 2);
        return [k, k * 0.94, k * 0.96];
      },
    ),
    0.6,
  );

  // 2. Нейросекреторные ядра гипоталамуса (супраоптическое, паравентрикулярное, аркуатное)
  const nucleiGeo = safeMerge([
    // паравентрикулярные ядра (окситоцин и АДГ)
    ellipGeo([0.36, 1.98, 0.28], [0.16, 0.24, 0.17], [0.1, 0, -0.15], 16, 12),
    ellipGeo([-0.36, 1.98, 0.28], [0.16, 0.24, 0.17], [0.1, 0, 0.15], 16, 12),
    // супраоптические ядра (над зрительным перекрёстом — АДГ)
    ellipGeo([0.46, 1.48, 0.64], [0.19, 0.14, 0.16], [0, -0.25, 0.1], 16, 12),
    ellipGeo([-0.46, 1.48, 0.64], [0.19, 0.14, 0.16], [0, 0.25, -0.1], 16, 12),
    // аркуатные / мелкоклеточные ядра (либерины и статины для аденогипофиза)
    ellipGeo([0.24, 1.30, 0.16], [0.18, 0.15, 0.20], [0, 0, -0.1], 14, 10),
    ellipGeo([-0.24, 1.30, 0.16], [0.18, 0.15, 0.20], [0, 0, 0.1], 14, 10),
    // супрахиазматическое ядро — внутренние биологические часы!
    ellipGeo([0.14, 1.40, 0.96], [0.09, 0.08, 0.09], [0, 0, 0], 12, 10),
    ellipGeo([-0.14, 1.40, 0.96], [0.09, 0.08, 0.09], [0, 0, 0], 12, 10),
  ]);

  // 3. Зрительный перекрёст (Chiasma opticum) с нервами и трактами
  const opticGeo = safeMerge([
    // зрительные нервы спереди, сходящиеся в перекрёст
    tube(
      [
        [1.16, 1.23, 1.70],
        [0.64, 1.20, 1.44],
        [0.16, 1.18, 1.22],
        [-0.30, 1.20, 0.88],
        [-0.86, 1.26, 0.16],
        [-1.18, 1.34, -0.52],
      ],
      (t) => 0.13 + 0.03 * Math.exp(-(((t - 0.42) / 0.16) ** 2)),
      { radial: 12, segments: 44 },
    ),
    tube(
      [
        [-1.16, 1.23, 1.70],
        [-0.64, 1.20, 1.44],
        [-0.16, 1.18, 1.22],
        [0.30, 1.20, 0.88],
        [0.86, 1.26, 0.16],
        [1.18, 1.34, -0.52],
      ],
      (t) => 0.13 + 0.03 * Math.exp(-(((t - 0.42) / 0.16) ** 2)),
      { radial: 12, segments: 44 },
    ),
    ellipGeo([0, 1.18, 1.18], [0.34, 0.14, 0.22], [0, 0, 0], 16, 12),
  ]);

  // 4. Ножка гипофиза (воронка / Infundibulum)
  const stalkGeo = tube(
    [
      [0, 0.98, 0.26],
      [0, 0.56, 0.26],
      [0, 0.12, 0.22],
      [0, -0.32, 0.06],
    ],
    (t) => 0.34 * (1 - 0.45 * t) + 0.06 * Math.pow(t, 2),
    { radial: 18, segments: 28 },
  );

  // 5. Портальная система гипофиза: верхние гипофизарные артерии + первичное сплетение + портальные вены + вторичная сеть
  const portalParts: BufferGeometry[] = [];
  for (const s of [1, -1] as const) {
    // верхняя гипофизарная артерия, мягко огибающая срединное возвышение
    portalParts.push(
      tube(
        [
          [0.92 * s, 0.52, 0.36],
          [0.58 * s, 0.72, 0.44],
          [0.32 * s, 0.78, 0.44],
          [0.14 * s, 0.74, 0.48],
        ],
        (t) => 0.046 * (1 - 0.35 * t),
        { radial: 9, segments: 24 },
      ),
    );
    // первичные капиллярные петли в срединном возвышении
    portalParts.push(
      tube(
        [
          [0.32 * s, 0.80, 0.40],
          [0.24 * s, 1.02, 0.34],
          [0.10 * s, 0.94, 0.42],
          [0.18 * s, 0.68, 0.46],
        ],
        0.022,
        { radial: 7, segments: 20 },
      ),
    );
    // длинные портальные вены по передней поверхности ножки
    for (const lane of [0.09, 0.21, 0.31]) {
      portalParts.push(
        tube(
          [
            [lane * s, 0.76, 0.46 - lane * 0.25],
            [(lane * 0.85) * s, 0.35, 0.48 - lane * 0.2],
            [(lane * 1.15) * s, -0.14, 0.62 - lane * 0.15],
            [(lane * 2.0) * s, -0.58, 0.76 - lane * 0.2],
            [(lane * 2.2) * s, -0.92, 0.62 - lane * 0.2],
          ],
          0.024,
          { radial: 7, segments: 26 },
        ),
      );
    }
    // поперечные анастомозы вторичного капиллярного сплетения в аденогипофизе
    portalParts.push(
      tube(
        [
          [0.16 * s, -0.45, 0.84],
          [0.45 * s, -0.58, 0.82],
          [0.64 * s, -0.78, 0.68],
          [0.42 * s, -0.98, 0.56],
        ],
        0.020,
        { radial: 7, segments: 22 },
      ),
      // выносящая гипофизарная вена, огибающая боковую стенку доли к пещеристому синусу
      tube(
        [
          [0.54 * s, -0.78, 0.46],
          [0.78 * s, -0.80, 0.24],
          [0.88 * s, -0.82, -0.08],
        ],
        (t) => 0.030 + 0.012 * t,
        { radial: 8, segments: 16 },
      ),
    );
  }
  const portalGeo = safeMerge(portalParts);

  // 6. Гипоталамо-гипофизарный нервный тракт (аксоны к задней доле + тельца Херринга)
  const tractParts: BufferGeometry[] = [];
  for (const s of [1, -1] as const) {
    // аксоны от паравентрикулярного ядра
    tractParts.push(
      tube(
        [
          [0.36 * s, 1.96, 0.26],
          [0.22 * s, 1.34, 0.18],
          [0.11 * s, 0.68, 0.14],
          [0.09 * s, 0.05, 0.03],
          [0.16 * s, -0.56, -0.26],
          [0.24 * s, -0.78, -0.40],
        ],
        0.024,
        { radial: 7, segments: 32 },
      ),
      // аксоны от супраоптического ядра
      tube(
        [
          [0.44 * s, 1.46, 0.60],
          [0.22 * s, 1.04, 0.30],
          [0.08 * s, 0.44, 0.10],
          [0.06 * s, -0.22, -0.10],
          [0.10 * s, -0.68, -0.36],
        ],
        0.022,
        { radial: 7, segments: 28 },
      ),
      // тельца Херринга (концевые расширения аксонов с запасом АДГ и окситоцина)
      ellipGeo([0.24 * s, -0.79, -0.41], [0.075, 0.075, 0.075], [0, 0, 0], 12, 10),
      ellipGeo([0.11 * s, -0.69, -0.37], [0.068, 0.068, 0.068], [0, 0, 0], 12, 10),
    );
  }
  const tractGeo = safeMerge(tractParts);

  // 7. Передняя доля гипофиза (аденогипофиз: дистальная, промежуточная и туберальная части)
  const adenoOuter = smooth(
    0.16,
    E([0, -0.68, 0.48], [0.80, 0.56, 0.48], 0.35),
    mirrored(E([0.42, -0.68, 0.42], [0.46, 0.50, 0.44], 0.3)),
    // туберальная часть (воротник вокруг передней стороны ножки)
    capsule([0, -0.28, 0.36], [0, 0.48, 0.38], 0.24, 0.15),
  );
  // выемка сзади для тесного прилегания нейрогипофиза
  const adenoCarved = smoothSubtract(0.10, adenoOuter, E([0, -0.66, -0.32], [0.56, 0.52, 0.44], 0.3));
  const adenoGeo = attachOrganicUv(
    organicTint(
      sdfMesh(textured(adenoCarved, 5.5, 0.018, 0.25), [-1.05, -1.40, -0.10], [1.05, 0.70, 1.15], 0.055, 0.08),
      (x, y) => {
        const k = 0.89 + 0.11 * wave(x * 5 + y * 5, 5, 3);
        return [k, k * 0.91, k * 0.90];
      },
    ),
    0.85,
  );

  // 8. Задняя доля гипофиза (нейрогипофиз)
  const neuroF = smooth(
    0.12,
    E([0, -0.66, -0.32], [0.54, 0.48, 0.40], 0.3),
    capsule([0, -0.32, -0.14], [0, 0.25, 0.08], 0.20, 0.14),
  );
  const neuroGeo = attachOrganicUv(
    organicTint(
      sdfMesh(wobble(neuroF, 4.5, 0.016, 0.2), [-0.75, -1.30, -0.90], [0.75, 0.45, 0.35], 0.055, 0.07),
      (x, y) => {
        const k = 0.92 + 0.08 * wave(x * 4 + y * 6, 4, 2);
        return [k, k * 0.96, k * 0.92];
      },
    ),
    0.9,
  );

  // 9. Эпифиз (шишковидная железа) с характерным чешуйчатым рельефом и поводком
  const pinealBase = smooth(
    0.10,
    Er([0, 1.88, -2.52], [0.40, 0.36, 0.62], [0.22, 0, 0], 0.3),
    E([0, 1.80, -2.92], [0.24, 0.22, 0.30], 0.25),
    mirrored(capsule([0.14, 1.90, -2.14], [0.26, 1.94, -1.55], 0.12, 0.11)),
  );
  const pinealScaly: Sdf = (x, y, z) => {
    const d = pinealBase(x, y, z);
    if (d > 0.22 || d < -0.25) return d;
    return d - 0.028 * Math.sin(z * 16 + x * 11) * Math.cos(y * 16 - x * 10);
  };
  const pinealGeo = attachOrganicUv(
    organicTint(
      sdfMesh(pinealScaly, [-0.62, 1.32, -3.35], [0.62, 2.45, -1.40], 0.05, 0.07),
      (_x, y, z) => {
        const k = 0.88 + 0.12 * wave(z * 6 + y * 6, 4, 3);
        return [k, k * 0.90, k];
      },
    ),
    0.9,
  );

  // 10. Турецкое седло клиновидной кости (Sella turcica) + клиновидная пазуха снизу
  const sellaBase = smooth(
    0.18,
    // тело клиновидной кости
    E([0, -1.62, 0.15], [1.65, 0.68, 1.48], 0.5),
    // спинка седла (dorsum sellae) сзади
    Er([0, -0.68, -1.04], [0.85, 0.68, 0.22], [-0.18, 0, 0], 0.4),
    // парные задние клиновидные отростки
    mirrored(sphere([0.66, -0.14, -1.06], 0.18)),
    // бугорок седла спереди и передние клиновидные отростки
    Er([0, -0.96, 1.24], [1.10, 0.34, 0.28], [0.25, 0, 0], 0.4),
    mirrored(chainSdf([[0.95, -0.78, 1.24], [1.12, -0.44, 0.86]], [0.18, 0.13], 0.08)),
  );
  // гипофизарная ямка, в которой уютно лежит гипофиз
  const fossa = E([0, -0.66, 0.14], [0.96, 0.72, 0.96], 0.35);
  // клиновидная воздухоносная пазуха внутри тела кости
  const sinusF = E([0, -1.78, 0.44], [0.92, 0.38, 0.72], 0.3);
  const sellaGeo = attachOrganicUv(
    organicTint(
      sdfMesh(smoothSubtract(0.14, sellaBase, fossa, sinusF), [-1.85, -2.35, -1.55], [1.85, 0.20, 1.85], 0.075, 0.10),
      (x, y) => {
        const k = 0.90 + 0.10 * wave(x * 4 + y * 5, 4, 2);
        return [k, k * 0.97, k * 0.90];
      },
    ),
    0.65,
  );
  const sinusGeo = sdfMesh(sinusF, [-1.05, -2.25, -0.40], [1.05, -1.30, 1.25], 0.08);

  return {
    hypothalamus: [{ mat: 'hypothalamus', geo: hypoGeo }],
    'hypo-nuclei': [{ mat: 'hypoNuclei', geo: nucleiGeo }],
    'optic-chiasm': [{ mat: 'opticChiasm', geo: opticGeo }],
    'pituitary-stalk': [{ mat: 'pituitaryStalk', geo: stalkGeo }],
    'portal-system': [{ mat: 'portalVessel', geo: portalGeo }],
    'hypo-tract': [{ mat: 'nerveTract', geo: tractGeo }],
    adenohypophysis: [{ mat: 'adenohypophysis', geo: adenoGeo }],
    neurohypophysis: [{ mat: 'neurohypophysis', geo: neuroGeo }],
    'pineal-gland': [{ mat: 'pineal', geo: pinealGeo }],
    'sella-turcica': [
      { mat: 'bone', geo: sellaGeo },
      { mat: 'sinusGhost', geo: sinusGeo },
    ],
  };
}
