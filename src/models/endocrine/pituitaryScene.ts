/*
  Макродиорама «Гипоталамус, гипофиз и эпифиз» (увеличение примерно ×10 относительно фигуры тела).
  Локальные координаты: +z — вперёд (к зрительному перекрёсту), +y — вверх (к гипоталамусу),
  +x — влево от пациента. Центр сцены около [0, 0.3, -0.2].
*/

function organicTint(
  g: BufferGeometry,
  fn: (x: number, y: number, z: number) => [number, number, number],
): BufferGeometry {
  return tint(g, (x, y, z) => fn(x, y, z));
}

function chainSdf(pts: V3[], radii: number[], k = 0.08): Sdf {
  const segs: Sdf[] = [];
  for (let i = 0; i < pts.length - 1; i++) {
    segs.push(capsule(pts[i], pts[i + 1], radii[i], radii[i + 1]));
  }
  return smooth(k, ...segs);
}

